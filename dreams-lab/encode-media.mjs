import {execFileSync} from 'node:child_process';
import {readdir,stat} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('./',import.meta.url));
process.chdir(root);
const ffmpeg=process.argv[2]||'ffmpeg',directory=fileURLToPath(new URL('./.cache/media/lab3d/',import.meta.url));
const frames=(await readdir(directory)).filter(f=>/^\d{4}\.png$/.test(f)).sort();
if(frames.length!==840||frames.some((file,i)=>file!==String(i).padStart(4,'0')+'.png'))throw Error('Expected 840 consecutive Lab source frames.');
const input=['-y','-framerate','30','-i',`${directory}/%04d.png`];
execFileSync(ffmpeg,[...input,'-c:v','libx264','-crf','18','-preset','slow','-threads','2','-pix_fmt','yuv420p','-movflags','+faststart','docs/media/dreams-lab-3d-run.mp4'],{stdio:['ignore','ignore','pipe']});
execFileSync(ffmpeg,[...input,'-filter_complex','scale=1280:720:flags=lanczos,split[a][b];[a]palettegen=stats_mode=diff[p];[b][p]paletteuse=dither=none','-loop','0','docs/media/dreams-lab-3d-run.gif'],{stdio:['ignore','ignore','pipe']});
execFileSync(ffmpeg,['-y','-i',`${directory}/0360.png`,'-frames:v','1','-q:v','2','docs/media/dreams-lab-3d-run.jpg'],{stdio:['ignore','ignore','pipe']});
console.log(`840 source frames · 30 fps · GIF ${((await stat('docs/media/dreams-lab-3d-run.gif')).size/1e6).toFixed(2)} MB`);
